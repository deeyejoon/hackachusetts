"""Crisis-language detection.

This module provides a fast, dependency-free check that runs BEFORE any model
call. When a user's message matches a crisis pattern, the chat service
short-circuits with a fixed, human-reviewed response and never contacts the
language model.

The patterns are intentionally conservative and high-precision. This is a
safety net, not a clinical screening tool.
"""

import re

# Case-insensitive patterns indicating acute risk. Kept as compiled regexes so
# the check is cheap to run on every message.
_CRISIS_PATTERNS = [
    re.compile(pattern, re.IGNORECASE)
    for pattern in (
        r"kill myself",
        r"suicid(e|al)",
        r"end my life",
        r"want to die",
        r"hurt myself",
        r"self[-\s]?harm",
    )
]

# Fixed response returned on any crisis match. This text is reviewed by a human
# and must not be generated by the model.
CRISIS_RESPONSE = (
    "I'm really glad you told me. I'm not able to help with this myself, but "
    "please reach out right now to people who can:\n\n"
    "988 Suicide & Crisis Lifeline — call or text 988 (US)\n"
    "Crisis Text Line — text HOME to 741741\n\n"
    "You don't have to go through this alone."
)


def is_crisis_message(text: str) -> bool:
    """Return True if the text matches any crisis pattern.

    Args:
        text: The raw user message.

    Returns:
        True when the message appears to express acute self-harm or suicidal
        intent, else False.
    """
    if not text:
        return False
    return any(pattern.search(text) for pattern in _CRISIS_PATTERNS)
